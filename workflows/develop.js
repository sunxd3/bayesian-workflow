// Phase 3 — Model development. The full multi-round loop lives HERE, not in the
// orchestrator: stage pipeline, FIX budget, MCMC throttling, verdict audits,
// the question ledger, plateau guards, and round budgets are all code.
// Judgment happens INSIDE the loop as schema-constrained agent calls:
//
//   critic      — per-experiment statistical + domain assessment
//   strategist  — per-round: close questions, pick explorations, framework
//                 questioning, surface new structural questions, stop
//   refiner     — FIX (repair) and EXPLORE (extend/simplify) variants
//   designer    — experiments for newly surfaced questions
//   selector    — final comparison + coverage audit
//
// The strategist proposes; the script disposes. Every strategist decision is
// filtered through deterministic guards (budgets, plateau rule, caps), and every
// dropped decision is logged — no silent truncation.
//
// Invoked by the orchestrator (see the `orchestration` skill) as:
//
//   Workflow({
//     scriptPath: "${CLAUDE_PLUGIN_ROOT}/workflows/develop.js",
//     args: {
//       projectDir, dataPath,                    // absolute paths
//       questions:   [{id, statement, contrast?}, ...],          // from design.js
//       experiments: [{id, questionId, spec, baseline?, context?}, ...],
//       planPath: "...",       // default: <projectDir>/design/experiment_plan.md
//       edaReportPath: "...",  // default: <projectDir>/eda/eda_report.html
//       metric: { name, definition },  // the plan's ranking metric (design.js
//                              // plan.ranking_metric); default: observation-level
//                              // PSIS-LOO. The script never assumes WHICH metric —
//                              // only its shape (score ± se, higher is better).
//       bounds: "...",         // the plan's outcome plausibility bounds
//                              // (design.js plan.plausibility_bounds) — the prior
//                              // gate's audited number is computed against these
//       limits: { maxRounds: 5, refineBudget: 2, maxMcmcConcurrency: 3,
//                 explorePerQuestion: 2, maxNewQuestions: 2,
//                 maxTotalExperiments: 24, budgetReserve: 60000 },
//     },
//   })
//
// Crash recovery is file-based: stage agents follow the validation-protocol
// status.json contract, so re-running with the same args re-verifies completed
// stages in seconds instead of re-fitting. Same-session, pass resumeFromRunId
// to also replay completed agent calls from the journal. Do NOT edit this file
// while a run that references it is in flight.


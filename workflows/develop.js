function registerExperiment(e) {
  ledger.experiments[e.id] = {
    id: e.id, questionId: e.questionId, baseline: !!e.baseline, parentId: e.parentId || null,
    spec: e.spec, status: 'pending', failed_at: null, dir: expDir(e.id), data_path: A.dataPath,
    score: null, score_se: null, critique_verdict: null,
  }
}

function foldResult(res) {
  // res.id is the final variant id (FIX variants replace their parent in place).
  if (!ledger.experiments[res.id]) registerExperiment({ id: res.id, questionId: res.question_id, spec: res.spec || '' })
  const rec = ledger.experiments[res.id]
  rec.status = res.status
  rec.failed_at = res.failed_at || null
  if (res.root_id !== res.id && ledger.experiments[res.root_id]) {
    ledger.experiments[res.root_id].status = 'superseded'
    rec.baseline = ledger.experiments[res.root_id].baseline
  }
  const fit = res.trail.filter((t) => t.stage === 'fit' && t.result && t.result.verdict === 'PASS').pop()
  if (res.status === 'terminal' && fit) {
    rec.critique_verdict = res.critique ? res.critique.verdict : null
    // A score computed under a different metric than the plan's is not on the
    // shared scale — folding it would poison every ranking/plateau decision.
    if (fit.result.metric && fit.result.metric !== METRIC.name) {
      log(`⚠ ${res.id}: fit reported metric '${fit.result.metric}' ≠ plan metric '${METRIC.name}' — score excluded from trajectories and ranking. Fitter's stated reason: ${fit.result.metric_note || 'NONE GIVEN'}`)
    } else {
      rec.score = fit.result.score
      rec.score_se = fit.result.score_se
      const q = ledger.questions[rec.questionId]
      if (q) {
        q.trajectory.push({ id: res.id, score: rec.score, se: rec.score_se, verdict: rec.critique_verdict })
        updatePlateau(q)
      }
    }
  }
}

// Plateau rule (recomputed, not latched): the latest variant must beat the best
// of its predecessors by more than 2·SE(diff). Unpaired SEs are a crude upper
// bound — fine for a guard; the selector does the proper paired comparison.
function updatePlateau(q) {
  const t = q.trajectory.filter((x) => Number.isFinite(x.score) && Number.isFinite(x.se))
  if (t.length < 2) { q.plateaued = false; return }
  const latest = t[t.length - 1]
  const bestPrev = t.slice(0, -1).reduce((a, b) => (b.score > a.score ? b : a))
  q.plateaued = latest.score - bestPrev.score < 2 * Math.sqrt(latest.se ** 2 + bestPrev.se ** 2)
}

function currentBest() {
  return Object.values(ledger.experiments)
    .filter((e) => e.status === 'terminal' && (e.critique_verdict === 'VIABLE' || e.critique_verdict === 'CONCERNS') && Number.isFinite(e.score))
    .reduce((a, b) => (a === null || b.score > a.score ? b : a), null)
}

// ---------------------------------------------------------------------------
// Verdict-vs-numbers audits. Fit thresholds are hard (they define PASS), so an
// inconsistent PASS is DEMOTED to FAIL and enters the FIX loop. The other
// stages' thresholds are heuristics, so inconsistencies are flagged for the
// strategist rather than acted on.
// ---------------------------------------------------------------------------
function auditGate(stageKey, r, expId) {
  if (!r || r.verdict !== 'PASS') return r
  // Provenance: a stage that read a different dataset than dispatched produces
  // results incomparable with every sibling experiment. For fit that poisons
  // the ranking itself — demote; elsewhere flag for the strategist.
  if (r.data_path && r.data_path !== A.dataPath) {
    if (stageKey === 'fit') {
      log(`⚠ ${expId}: fit PASS demoted to FAIL — fit read '${r.data_path}', dispatched '${A.dataPath}'`)
      return { ...r, verdict: 'FAIL', cross_check: 'DEMOTED', rationale: `Audit demotion: wrong dataset (read ${r.data_path}, dispatched ${A.dataPath}). Agent rationale: ${r.rationale}` }
    }
    return flagInconsistent(r, expId, stageKey, `data_path mismatch: read ${r.data_path}`)
  }
  if ((stageKey === 'fit' || stageKey === 'prior') && !r.data_path) {
    r = flagInconsistent(r, expId, stageKey, 'data_path missing — provenance unverifiable')
  }
  if (stageKey === 'fit' && !r.metric) {
    r = flagInconsistent(r, expId, stageKey, `metric name missing — score assumed to be ${METRIC.name}`)
  }
  const missing = (PASS_REQUIRES[stageKey] || []).filter((k) => !Number.isFinite(r[k]))
  if (missing.length) {
    // Fit numbers define PASS and feed the ledger's score trajectories — a fit
    // PASS without them is unverifiable, so it fails into the FIX path. Other
    // stages' missing numbers are flagged for the strategist instead.
    if (stageKey === 'fit') {
      log(`⚠ ${expId}: fit PASS demoted to FAIL — audited numbers missing: ${missing.join(', ')}`)
      return { ...r, verdict: 'FAIL', cross_check: 'DEMOTED', rationale: `Audit demotion: PASS reported without ${missing.join(', ')}. Agent rationale: ${r.rationale}` }
    }
    return flagInconsistent(r, expId, stageKey, `audited numbers missing: ${missing.join(', ')}`)
  }
  if (stageKey === 'fit') {
    const hard = []
    if (r.rhat_max > 1.01) hard.push(`rhat_max=${r.rhat_max}`)
    if (r.divergences > 0) hard.push(`divergences=${r.divergences}`)
    if (r.ess_min < 400) hard.push(`ess_min=${r.ess_min}`)
    if (hard.length) {
      log(`⚠ ${expId}: fit PASS demoted to FAIL — ${hard.join(', ')} violate hard thresholds`)
      return { ...r, verdict: 'FAIL', cross_check: 'DEMOTED', rationale: `Audit demotion (${hard.join(', ')}). Agent rationale: ${r.rationale}` }
    }
    if (r.pareto_k_bad_pct > 10) return flagInconsistent(r, expId, stageKey, `pareto_k_bad_pct=${r.pareto_k_bad_pct}% > 10%`)
    return r
  }
  const soft = {
    prior: () => r.extreme_draw_pct > 10 && `extreme_draw_pct=${r.extreme_draw_pct}% > 10%`,
    recovery: () => (r.coverage_90 < 0.6 && `coverage_90=${r.coverage_90} < 0.6`) || (r.max_bias_z > 3 && `max_bias_z=${r.max_bias_z} > 3`),
    ppc: () => r.coverage_90 < 0.5 && `coverage_90=${r.coverage_90} < 0.5`,
  }[stageKey]
  const reason = soft && soft()
  return reason ? flagInconsistent(r, expId, stageKey, reason) : r
}

function flagInconsistent(r, expId, stageKey, reason) {
  log(`⚠ ${expId}: ${stageKey} PASS inconsistent with reported numbers (${reason})`)
  return { ...r, cross_check: `INCONSISTENT: ${reason}` }
}


function semaphore(n) {
  let active = 0
  const waiters = []
  return async (fn) => {
    while (active >= n) await new Promise((res) => waiters.push(res))
    active++
    try { return await fn() } finally {
      active--
      const w = waiters.shift()
      if (w) w()
    }
  }
}
const mcmcSlot = semaphore(L.maxMcmcConcurrency)

function dispatchStage(stage, exp) {
  const run = () => call(stage.agent, stage.prompt(exp, expDir(exp.id)), {
    label: `${exp.id}:${stage.key}`, phase: 'Validate', schema: stage.schema,
  })
  return stage.mcmc ? mcmcSlot(run) : run()
}

// ---------------------------------------------------------------------------
// Per-experiment lifecycle. FAIL with budget left → model-refiner (FIX) writes
// a NEW variant directory; the variant re-enters at the prior stage. Completed
// stage directories are immutable, so status.json records stay trustworthy.
// ---------------------------------------------------------------------------
async function runExperiment(exp0) {
  let exp = { ...exp0 }
  let budget = L.refineBudget
  const trail = []

  lifecycle: while (true) {
    for (const stage of STAGES) {
      let r = await dispatchStage(stage, exp)
      r = auditGate(stage.key, r, exp.id)
      trail.push({ experiment: exp.id, stage: stage.key, result: r })

      if (!r) {
        log(`${exp.id}: ${stage.key} agent lost — will auto-resubmit once next round`)
        return { id: exp.id, root_id: exp0.id, question_id: exp0.questionId, spec: exp.spec, context: exp.context, status: 'agent_lost', failed_at: stage.key, trail }
      }
      if (r.verdict === 'FAIL') {
        if (budget <= 0) {
          log(`${exp.id}: ${stage.key} FAIL, refine budget exhausted — skipping experiment`)
          return { id: exp.id, root_id: exp0.id, question_id: exp0.questionId, spec: exp.spec, context: exp.context, status: 'skipped', failed_at: stage.key, trail }
        }
        budget--
        const variantId = nextId(exp0.id, 'fix')
        log(`${exp.id}: ${stage.key} FAIL — model-refiner (FIX) → ${variantId} (budget left: ${budget})`)
        const ref = await call('model-refiner', `experiment_dir: ${expDir(exp.id)}
mode: FIX
output_dir: ${expDir(variantId)}

suggestions:
Experiment ${exp.id} FAILED the ${stage.key} stage.
Failure rationale: ${r.rationale}
Key numbers: ${r.key_numbers}`, {
          label: `${exp.id}:refine(${stage.key})`, phase: 'Validate', schema: REFINE_RESULT,
        })
        trail.push({ experiment: exp.id, stage: `refine(${stage.key})`, result: ref })
        if (!ref || ref.exhausted) {
          log(`${exp.id}: refiner ${ref ? 'reports options exhausted' : 'lost'} — skipping experiment`)
          return { id: exp.id, root_id: exp0.id, question_id: exp0.questionId, spec: exp.spec, context: exp.context, status: 'skipped', failed_at: stage.key, trail }
        }
        exp = {
          ...exp, id: variantId,
          context: `${exp.context ? exp.context + '\n' : ''}FIX after ${stage.key} failure of ${exp.id}: ${ref.changes_summary}`,
        }
        continue lifecycle // FIX variant re-enters at the prior stage
      }
      log(`${exp.id}: ${stage.key} PASS${r.from_cache ? ' (completed-work check)' : ''}${r.cross_check ? ' ⚠' : ''}`)
      if (stage.key === 'prior' && r.adjustments) {
        // In-place prior tuning changed model.stan; carry it so the ledger,
        // strategist digest, and refiners see the priors that actually ran.
        exp = { ...exp, context: `${exp.context ? exp.context + '\n' : ''}Prior tuning during ${stage.key} of ${exp.id}: ${r.adjustments}` }
      }
    }

    const critique = await call('critic', `experiment_dir: ${expDir(exp.id)}
experiment_plan_path: ${PLAN}
eda_report_path: ${EDA}
data_path: ${A.dataPath}${RETURN_NOTE}`, {
      label: `${exp.id}:critic`, phase: 'Validate', schema: CRITIC_RESULT,
    })
    trail.push({ experiment: exp.id, stage: 'critic', result: critique })
    log(`${exp.id}: critic ${critique ? critique.verdict : 'LOST'}`)
    return {
      id: exp.id, root_id: exp0.id, question_id: exp0.questionId, spec: exp.spec, context: exp.context,
      status: critique ? 'terminal' : 'agent_lost',
      failed_at: critique ? undefined : 'critic',
      trail, critique,
    }
  }
}

// ---------------------------------------------------------------------------
// Strategist digest — a compact, script-composed view of the ledger and the
// round. The strategist reads report files for depth; this is the index.
// ---------------------------------------------------------------------------
function strategistDigest(roundResults, round) {
  const qLines = Object.values(ledger.questions).map((q) => {
    const traj = q.trajectory.map((t) => `${t.id}: ${METRIC.name} ${t.score}±${t.se} [${t.verdict}]`).join('; ') || 'no terminal variants yet'
    const flags = [
      q.plateaued && 'PLATEAUED (no further EXPLORE permitted)',
      q.exploreCount >= L.explorePerQuestion && 'explore budget spent',
    ].filter(Boolean).join(', ')
    return `${q.id} [${q.status}${flags ? '; ' + flags : ''}] ${q.statement}\n  trajectory: ${traj}`
  }).join('\n')

  const rLines = roundResults.map((r) => {
    if (r.status !== 'terminal') return `${r.id}: ${r.status} at ${r.failed_at}`
    const flags = r.trail.filter((t) => t.result && t.result.cross_check).map((t) => `${t.stage}: ${t.result.cross_check}`).join('; ')
    const c = r.critique
    return `${r.id} (${r.question_id}): critique ${c.verdict} — ${c.top_concern}` +
      (c.suggestions.length ? `\n  suggestions: ${c.suggestions.join(' | ')}` : '') +
      (c.surprises.length ? `\n  surprises: ${c.surprises.join(' | ')}` : '') +
      (flags ? `\n  ⚠ audit flags: ${flags}` : '') +
      (c.report_path ? `\n  report: ${c.report_path}` : '')
  }).join('\n')

  return `Round ${round} of ${L.maxRounds}.

QUESTIONS
${qLines}

THIS ROUND
${rLines}

CONSTRAINTS (enforced by the calling script — decisions violating them are dropped)
- EXPLORE variants left per question: ${Object.values(ledger.questions).map((q) => `${q.id}: ${Math.max(0, L.explorePerQuestion - q.exploreCount)}`).join(', ')}
- New-question slots left: ${Math.max(0, L.maxNewQuestions - ledger.newQuestionCount)}
- Experiment slots left: ${Math.max(0, L.maxTotalExperiments - totalExperiments())}
- Plateaued questions accept no EXPLORE; close them or leave them.`
}

// ---------------------------------------------------------------------------
// Guarded application of strategist decisions.
// ---------------------------------------------------------------------------
// Variant/fix ids are globally unique per root: counters skip ids already in
// the ledger, so seeded variants and resubmitted lifecycles never clobber an
// existing experiment directory (whose status.json records must stay valid).
const variantCounter = {}
function nextId(rootId, kind) {
  const base = rootId.replace(/(_(?:v|fix)\d+)+$/, '')
  const key = `${base}:${kind}`
  let n = variantCounter[key] || 0
  let id
  do { id = `${base}_${kind}${++n}` } while (ledger.experiments[id])
  variantCounter[key] = n
  return id
}
const nextVariantId = (rootId) => nextId(rootId, 'v')

async function applyStrategy(strategy) {
  for (const c of strategy.close) {
    const q = ledger.questions[c.question_id]
    if (!q) { log(`✂ close '${c.question_id}' ignored: unknown question`); continue }
    if (q.status !== 'open') { log(`✂ close '${c.question_id}' ignored: already ${q.status}`); continue }
    q.status = 'resolved'
    q.resolution = c.resolution
    log(`${q.id} resolved: ${c.resolution}`)
  }

  // On stop, closes above still apply, but no new work is dispatched — a
  // strategist that says stop AND proposes work is contradictory; stop wins.
  if (strategy.stop) {
    if (strategy.explore.length || strategy.new_questions.length) {
      log(`✂ strategist stop: skipping ${strategy.explore.length} explore(s) and ${strategy.new_questions.length} new question(s) it also proposed`)
    }
    return []
  }

  const work = []

  for (const x of strategy.explore) {
    const parent = ledger.experiments[x.parent_id]
    const q = parent && ledger.questions[parent.questionId]
    const veto =
      !parent ? 'unknown parent' :
      parent.status !== 'terminal' ? `parent is ${parent.status}` :
      !q ? 'parent has no question' :
      q.status !== 'open' ? `question ${q.id} is ${q.status}` :
      q.plateaued ? `question ${q.id} plateaued` :
      q.exploreCount >= L.explorePerQuestion ? `question ${q.id} explore budget spent` :
      totalExperiments() >= L.maxTotalExperiments ? 'experiment cap reached' : null
    if (veto) { log(`✂ explore from ${x.parent_id} dropped: ${veto}`); continue }
    q.exploreCount++
    const vid = nextVariantId(parent.id)
    work.push(() => exploreVariant(parent, x.suggestions, vid))
  }

  for (const nq of strategy.new_questions) {
    if (ledger.newQuestionCount >= L.maxNewQuestions) { log(`✂ new question dropped (slots spent): ${nq.statement}`); continue }
    if (totalExperiments() >= L.maxTotalExperiments) { log(`✂ new question dropped (experiment cap): ${nq.statement}`); continue }
    const best = currentBest()
    if (!best) { log(`✂ new question dropped (no viable best model to baseline from): ${nq.statement}`); continue }
    ledger.newQuestionCount++
    const qid = `q${Object.keys(ledger.questions).length + 1}`
    ledger.questions[qid] = {
      id: qid, statement: nq.statement, contrast: nq.rationale,
      status: 'open', resolution: null, plateaued: false, exploreCount: 0, trajectory: [],
    }
    log(`new question ${qid}: ${nq.statement}`)
    work.push(() => designQuestion(qid, nq, best))
  }

  return (await parallel(work.map((w) => () => w()))).filter(Boolean).flat()
}

async function exploreVariant(parent, suggestions, vid) {
  const ref = await call('model-refiner', `experiment_dir: ${parent.dir}
mode: EXPLORE
output_dir: ${expDir(vid)}

suggestions:
${suggestions.join('\n')}`, {
    label: `explore:${vid}`, phase: 'Extend', schema: REFINE_RESULT,
  })
  if (!ref || ref.exhausted) {
    log(`explore ${vid}: refiner ${ref ? 'reports options exhausted' : 'lost'} — variant not created`)
    return null
  }
  return [{
    id: vid, questionId: parent.questionId, baseline: false, parentId: parent.id,
    spec: `EXPLORE variant of ${parent.id}. Base spec:\n${parent.spec}\n\nChanges: ${ref.changes_summary}`,
    context: `EXPLORE from ${parent.id}: ${ref.changes_summary}`,
  }]
}

async function designQuestion(qid, nq, best) {
  const d = await call('model-designer', `question_id: ${qid}
question: ${nq.statement}
contrast: ${nq.rationale}
baseline_spec (the CURRENT BEST validated model — build on what has been learned, not the original Phase 2 baseline):
${best.spec}
baseline_dir: ${best.dir}

plan_path: ${PLAN}
eda_dir: ${EDA.replace(/\/[^/]*$/, '')}
output_dir: ${A.projectDir}/design/designer_${qid}
max_experiments: 2`, {
    label: `design:${qid}`, phase: 'Extend', schema: DESIGN_RESULT,
  })
  if (!d) { log(`design ${qid}: designer lost — question stays open with no experiments`); return null }
  return d.experiments.slice(0, 2).map((e, j) => ({
    id: `${qid}_e${j + 1}`, questionId: qid, baseline: j === 0,
    spec: e.spec, context: e.purpose_in_sequence,
  }))
}

// ---------------------------------------------------------------------------
// Selection (+ at most one coverage-gap pass).
// ---------------------------------------------------------------------------
async function runSelector(label) {
  const dirs = Object.values(ledger.experiments)
    .filter((e) => e.status === 'terminal' && (e.critique_verdict === 'VIABLE' || e.critique_verdict === 'CONCERNS'))
    .map((e) => e.dir)
  if (!dirs.length) return null
  const qDigest = Object.values(ledger.questions)
    .map((q) => `${q.id} [${q.status}] ${q.statement}${q.resolution ? ` — resolution: ${q.resolution}` : ''}`).join('\n')
  return call('model-selector', `experiment_dirs:
${dirs.join('\n')}
experiment_plan_path: ${PLAN}
eda_report_path: ${EDA}
output_dir: ${A.projectDir}/experiments
ranking_metric: ${METRIC.name} — ${METRIC.definition}
data_path (every listed experiment was validated against this dataset): ${A.dataPath}

Question ledger:
${qDigest}${RETURN_NOTE}`, {
    label, phase: 'Select', schema: SELECT_RESULT,
  })
}

// ---------------------------------------------------------------------------
// The round loop.
// ---------------------------------------------------------------------------
log(`Phase 3: ${A.experiments.length} seed experiment(s), ${A.questions.length} question(s); limits: rounds ${L.maxRounds}, MCMC ${L.maxMcmcConcurrency}, refine ${L.refineBudget}, explore/question ${L.explorePerQuestion}`)

A.experiments.forEach(registerExperiment)
let queue = A.experiments.map((e) => ({ ...e }))
const resubmitted = {}
const allResults = []
let round = 0
let stopReason = null

while (queue.length && round < L.maxRounds) {
  round++
  log(`Round ${round}: ${queue.map((e) => e.id).join(', ')}`)
  const results = (await parallel(queue.map((e) => () => runExperiment(e)))).filter(Boolean)
  allResults.push(...results)
  results.forEach(foldResult)
  queue = []

  // Deterministic post-round rules — before any judgment is consulted.
  for (const r of results) {
    // Baseline failed pre-fit after its FIX attempts → the question is untestable as designed.
    if (r.status === 'skipped' && ['prior', 'recovery'].includes(r.failed_at)) {
      const root = ledger.experiments[r.root_id]
      const q = root && root.baseline && ledger.questions[root.questionId]
      if (q && q.status === 'open') {
        q.status = 'abandoned'
        q.resolution = `baseline ${r.id} failed pre-fit at ${r.failed_at} after refinement — question untestable as designed`
        log(`${q.id} abandoned: ${q.resolution}`)
      }
    }
    // Harness losses get one automatic resubmission of the LAST variant (its
    // completed stages short-circuit on status.json, so it resumes mid-pipeline).
    if (r.status === 'agent_lost' && !resubmitted[r.root_id]) {
      resubmitted[r.root_id] = true
      const orig = ledger.experiments[r.root_id]
      queue.push({
        id: r.id, questionId: orig.questionId, baseline: orig.baseline, spec: r.spec,
        context: `${r.context ? r.context + '\n' : ''}Resubmitted after a harness loss at the ${r.failed_at} stage — completed stages short-circuit on status.json.`,
      })
      log(`${r.id}: auto-resubmitted after harness loss`)
    }
  }
  // Drop queued siblings of abandoned questions.
  queue = queue.filter((e) => {
    const q = ledger.questions[e.questionId]
    if (q && q.status === 'abandoned') { log(`✂ ${e.id} dropped: question ${e.questionId} abandoned`); return false }
    return true
  })

  if (budget.total && budget.remaining() < L.budgetReserve) {
    stopReason = `token budget reserve reached (${Math.round(budget.remaining() / 1000)}k left)`
    log(stopReason + ' — proceeding to selection')
    break
  }

  const strategy = await call('strategist', `${strategistDigest(results, round)}

experiment_plan_path: ${PLAN}
eda_report_path: ${EDA}
experiments_dir: ${A.projectDir}/experiments
output_dir: ${A.projectDir}/experiments/strategy
round: ${round}

Assess the round, then decide: which questions to close, which EXPLORE variants are worth a round, whether any surprise warrants a genuinely NEW structural question, and whether to stop. Read critique reports before trusting one-line summaries. Framework questioning is yours: ask whether the population of models is the right class for this DGP at all.`, {
    label: `strategy:round${round}`, phase: 'Judge', schema: STRATEGY_RESULT,
  })

  if (!strategy) {
    stopReason = 'strategist lost — fail-safe stop'
    log(stopReason + '; proceeding to selection with completed work')
    break
  }
  if (strategy.framework_concern) log(`framework concern: ${strategy.framework_concern}`)

  const newWork = await applyStrategy(strategy)
  newWork.forEach(registerExperiment)
  queue.push(...newWork)

  if (strategy.stop) {
    stopReason = 'strategist: reasonable modifications have stopped helping'
    if (queue.length) log(`strategist stop overrides ${queue.length} queued item(s): ${queue.map((e) => e.id).join(', ')}`)
    queue = []
  } else if (!queue.length) {
    stopReason = 'no new work proposed'
  }
}
if (round >= L.maxRounds && queue.length) {
  stopReason = `round cap ${L.maxRounds} reached with work still queued: ${queue.map((e) => e.id).join(', ')}`
  log(`✂ ${stopReason}`)
}

// --- Selection, with at most one coverage-gap pass ---------------------------
let selection = await runSelector('select')
if (!selection) {
  log('no VIABLE/CONCERNS experiments to select from — returning ledger for orchestrator triage')
} else if (selection.coverage === 'GAPS' && selection.gaps.length && totalExperiments() < L.maxTotalExperiments
  && !(budget.total && budget.remaining() < L.budgetReserve)) {
  const best = currentBest()
  if (!best) {
    log('coverage GAPS but no viable best model to baseline gap experiments from — leaving gaps to the orchestrator')
  } else {
    log(`coverage GAPS: ${selection.gaps.join(' | ')} — one gap pass`)
    if (selection.gaps.length > 2) log(`✂ gap pass capped at 2 of ${selection.gaps.length} gaps`)
    const gapDefs = selection.gaps.slice(0, 2).map((g, i) => ({ qid: `gap${i + 1}`, statement: g }))
    for (const gd of gapDefs) {
      ledger.questions[gd.qid] = { id: gd.qid, statement: gd.statement, contrast: 'selector coverage audit', status: 'open', resolution: null, plateaued: false, exploreCount: 0, trajectory: [] }
    }
    const gapWork = (await parallel(gapDefs.map((gd) => () =>
      designQuestion(gd.qid, { statement: gd.statement, rationale: 'selector coverage audit' }, best),
    ))).filter(Boolean).flat()
    gapWork.forEach(registerExperiment)
    if (gapWork.length) {
      const gapResults = (await parallel(gapWork.map((e) => () => runExperiment(e)))).filter(Boolean)
      allResults.push(...gapResults)
      gapResults.forEach(foldResult)
      selection = (await runSelector('select:post-gap')) || selection
    }
  }
}

// The selector's pick must be a real experiment — an id it misremembered
// would poison the report phase's selectedModelDir.
if (selection && !ledger.experiments[selection.best_model_id]) {
  const fb = currentBest()
  log(`⚠ selector best_model_id '${selection.best_model_id}' not in ledger — falling back to ${fb ? fb.id : 'none'}`)
  if (fb) selection = { ...selection, best_model_id: fb.id }
}

const trailStages = allResults.flatMap((r) => r.trail)
return {
  selection,
  stop_reason: stopReason,
  ledger: {
    metric: ledger.metric,
    data_path: ledger.data_path,
    questions: Object.values(ledger.questions),
    experiments: Object.values(ledger.experiments),
  },
  counts: {
    rounds: round,
    experiments: totalExperiments(),
    terminal: Object.values(ledger.experiments).filter((e) => e.status === 'terminal').length,
    skipped: Object.values(ledger.experiments).filter((e) => e.status === 'skipped' || e.status === 'agent_lost').length,
    cached_stages: trailStages.filter((t) => t.result && t.result.from_cache).length,
  },
}

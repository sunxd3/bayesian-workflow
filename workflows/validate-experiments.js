// Bundled Workflow script: one round of the Phase 3 validation pipeline.
//
// Invoked by the orchestrator (see the `orchestration` skill) as:
//
//   Workflow({
//     scriptPath: "${CLAUDE_PLUGIN_ROOT}/workflows/validate-experiments.js",
//     args: {
//       projectDir: "/abs/path/to/project",
//       dataPath: "/abs/path/to/data.csv",
//       experiments: [{ id: "exp_1", spec: "<model spec text from experiment_plan.md>",
//                       context: "<optional carry-forward notes>" }, ...],
//       experimentPlanPath: "...",   // default: <projectDir>/design/experiment_plan.md
//       edaReportPath: "...",        // default: <projectDir>/eda/eda_report.html
//       maxMcmcConcurrency: 3,       // gate on recovery + fit stages (MCMC-heavy)
//       refineBudget: 2,             // FIX invocations per experiment lifecycle
//     },
//   })
//
// The script owns stage sequencing, the FIX-refine budget, MCMC throttling, and
// verdict-vs-numbers cross-checks. The orchestrator owns everything judgmental:
// reading critiques, EXPLORE variants, new structural questions, model selection.
// Experiments the script returns as `skipped`/`agent_lost` are the orchestrator's
// to triage at the round boundary.
//
// Crash recovery is file-based: stage agents follow the validation-protocol
// status.json contract, so re-running a round re-verifies completed stages in
// seconds instead of re-fitting. Do NOT edit this file while a run that
// references it is in flight — mid-flight edits can invalidate journal replay.

export const meta = {
  name: 'validate-experiments',
  description: 'One round of the Bayesian validation pipeline: prior → recovery → fit → ppc → critique per experiment, with budgeted FIX refinement',
  whenToUse: 'Dispatched by the bayesian-workflow orchestrator during Phase 3. Not intended for direct use.',
  phases: [
    { title: 'Validate', detail: 'experiments flow through the 5-stage pipeline independently' },
  ],
}

// args may arrive as a JSON string depending on harness version — parse defensively.
const A = typeof args === 'string' ? JSON.parse(args) : args
if (!A || !A.projectDir || !A.dataPath || !Array.isArray(A.experiments) || A.experiments.length === 0) {
  throw new Error('args must be {projectDir, dataPath, experiments: [{id, spec, context?}], experimentPlanPath?, edaReportPath?, maxMcmcConcurrency?, refineBudget?}')
}
const PLAN = A.experimentPlanPath || `${A.projectDir}/design/experiment_plan.md`
const EDA = A.edaReportPath || `${A.projectDir}/eda/eda_report.html`
const REFINE_BUDGET = A.refineBudget ?? 2
const AGENT = (name) => `bayesian-workflow:${name}`

// ---------------------------------------------------------------------------
// Structured-output schemas. `rationale` first: models emit properties in
// schema order, so the reasoning is committed before the verdict.
// ---------------------------------------------------------------------------
const GATE_RESULT = {
  type: 'object',
  properties: {
    rationale: { type: 'string', description: 'One short paragraph: the evidence behind the verdict' },
    verdict: { enum: ['PASS', 'FAIL'] },
    from_cache: { type: 'boolean', description: 'true iff returned via the validation-protocol completed-work check without redoing work' },
    key_numbers: { type: 'string', description: 'One dense line: the numbers behind the verdict' },
    rhat_max: { type: 'number' },
    ess_min: { type: 'number' },
    divergences: { type: 'integer' },
    report_path: { type: 'string' },
  },
  required: ['rationale', 'verdict', 'from_cache', 'key_numbers'],
}

const CRITIQUE_RESULT = {
  type: 'object',
  properties: {
    rationale: { type: 'string' },
    verdict: { enum: ['VIABLE', 'CONCERNS', 'BROKEN'] },
    top_concern: { type: 'string', description: 'The single highest-priority concern, one line' },
    suggestions: { type: 'array', items: { type: 'string' }, description: 'Concrete improvement suggestions, priority order, empty if none' },
    new_structural_question: { type: 'string', description: 'Set ONLY if the evidence genuinely raises a new structural question' },
    from_cache: { type: 'boolean' },
    report_path: { type: 'string' },
  },
  required: ['rationale', 'verdict', 'top_concern', 'suggestions', 'from_cache'],
}

const REFINE_RESULT = {
  type: 'object',
  properties: {
    rationale: { type: 'string' },
    changes_summary: { type: 'string', description: 'What changed in the variant and the expected diagnostic improvement' },
    exhausted: { type: 'boolean', description: 'true if no meaningful fix exists (per the exhaustion clause in your instructions)' },
  },
  required: ['rationale', 'changes_summary', 'exhausted'],
}

// ---------------------------------------------------------------------------
// Stage dispatch. Prompts follow each agent's `SIGNATURE` — the agents load
// their own skills and know the methodology; the dispatch only supplies args.
// ---------------------------------------------------------------------------
const RETURN_NOTE = `
Return your result via structured output. Set from_cache=true only if you short-circuited on an existing status.json (validation-protocol Step 3).`

const STAGES = [
  {
    key: 'prior', agent: 'prior-predictive-checker', mcmc: false,
    prompt: (exp, dir) => `experiment_dir: ${dir}
data_path: ${A.dataPath}
output_dir: ${dir}/prior_predictive

Model spec for this experiment (author ${dir}/model.stan from it if absent):
${exp.spec}
${exp.context ? `\nContext from the orchestrator:\n${exp.context}` : ''}${RETURN_NOTE}`,
  },
  {
    key: 'recovery', agent: 'fake-data-checker', mcmc: true,
    prompt: (exp, dir) => `experiment_dir: ${dir}
output_dir: ${dir}/simulation${RETURN_NOTE}`,
  },
  {
    key: 'fit', agent: 'model-fitter', mcmc: true,
    prompt: (exp, dir) => `experiment_dir: ${dir}
data_path: ${A.dataPath}
output_dir: ${dir}/fit
${exp.context ? `context: ${exp.context}` : ''}
In your structured result, report rhat_max, ess_min, and divergences as numbers.${RETURN_NOTE}`,
  },
  {
    key: 'ppc', agent: 'posterior-predictive-checker', mcmc: false,
    prompt: (exp, dir) => `experiment_dir: ${dir}
output_dir: ${dir}/posterior_predictive
experiment_plan_path: ${PLAN}${RETURN_NOTE}`,
  },
]

function semaphore(n) {
  let active = 0
  const waiters = []
  return async (fn) => {
    while (active >= n) await new Promise((res) => waiters.push(res))
    active++
    try { return await fn() } finally {
      active--
      const w = waiters.shift()
      if (w) w()
    }
  }
}
const mcmcSlot = semaphore(A.maxMcmcConcurrency ?? 3)

function dispatchStage(stage, exp) {
  const dir = `${A.projectDir}/experiments/${exp.id}`
  const run = () => agent(stage.prompt(exp, dir), {
    label: `${exp.id}:${stage.key}`,
    phase: 'Validate',
    agentType: AGENT(stage.agent),
    schema: GATE_RESULT,
  })
  return stage.mcmc ? mcmcSlot(run) : run()
}

function dispatchCritique(exp) {
  const dir = `${A.projectDir}/experiments/${exp.id}`
  return agent(`experiment_dir: ${dir}
experiment_plan_path: ${PLAN}
eda_report_path: ${EDA}
data_path: ${A.dataPath}${RETURN_NOTE}`, {
    label: `${exp.id}:critique`,
    phase: 'Validate',
    agentType: AGENT('critique'),
    schema: CRITIQUE_RESULT,
  })
}

function dispatchRefiner(exp, stageKey, failure, variantId) {
  const dir = `${A.projectDir}/experiments/${exp.id}`
  return agent(`experiment_dir: ${dir}
mode: FIX
output_dir: ${A.projectDir}/experiments/${variantId}

suggestions:
Experiment ${exp.id} FAILED the ${stageKey} stage.
Failure rationale: ${failure.rationale}
Key numbers: ${failure.key_numbers}`, {
    label: `${exp.id}:refine(${stageKey})`,
    phase: 'Validate',
    agentType: AGENT('model-refiner'),
    schema: REFINE_RESULT,
  })
}

// Deterministic audit: a PASS fit verdict must be consistent with the numbers
// the agent itself reported. Inconsistencies are flagged for the orchestrator,
// not silently accepted.
function crossCheckFit(r, expId) {
  if (r.verdict !== 'PASS') return r
  const bad = (r.rhat_max ?? 0) > 1.01 || (r.divergences ?? 0) > 0 || (r.ess_min ?? Infinity) < 400
  if (!bad) return r
  log(`⚠ ${expId}: fit PASS inconsistent with reported numbers (rhat_max=${r.rhat_max}, ess_min=${r.ess_min}, divergences=${r.divergences})`)
  return { ...r, cross_check: 'INCONSISTENT' }
}

// ---------------------------------------------------------------------------
// Per-experiment lifecycle. A FAIL with budget left triggers model-refiner
// (FIX), which writes a NEW variant directory; per the refiner's contract the
// variant re-enters the pipeline at the prior-predictive stage. Completed
// stage directories are immutable, so status.json records stay trustworthy.
// ---------------------------------------------------------------------------
async function runExperiment(exp0) {
  let exp = { ...exp0 }
  let budget = REFINE_BUDGET
  const trail = []

  lifecycle: while (true) {
    for (const stage of STAGES) {
      let r = await dispatchStage(stage, exp)
      if (r && stage.key === 'fit') r = crossCheckFit(r, exp.id)
      trail.push({ experiment: exp.id, stage: stage.key, result: r })

      if (!r) {
        log(`${exp.id}: ${stage.key} agent lost (terminal error or skipped) — orchestrator to triage`)
        return { id: exp.id, root_id: exp0.id, status: 'agent_lost', failed_at: stage.key, trail }
      }
      if (r.verdict === 'FAIL') {
        if (budget <= 0) {
          log(`${exp.id}: ${stage.key} FAIL, refine budget exhausted — skipping experiment`)
          return { id: exp.id, root_id: exp0.id, status: 'skipped', failed_at: stage.key, trail }
        }
        budget--
        const variantId = `${exp0.id}_fix${REFINE_BUDGET - budget}`
        log(`${exp.id}: ${stage.key} FAIL — model-refiner (FIX) → ${variantId} (budget left: ${budget})`)
        const ref = await dispatchRefiner(exp, stage.key, r, variantId)
        trail.push({ experiment: exp.id, stage: `refine(${stage.key})`, result: ref })
        if (!ref || ref.exhausted) {
          log(`${exp.id}: refiner ${ref ? 'reports options exhausted' : 'lost'} — skipping experiment`)
          return { id: exp.id, root_id: exp0.id, status: 'skipped', failed_at: stage.key, trail }
        }
        exp = {
          id: variantId,
          spec: exp.spec,
          context: `${exp.context ? exp.context + '\n' : ''}FIX after ${stage.key} failure of ${exp.id}: ${ref.changes_summary}`,
        }
        continue lifecycle // variant re-enters at the prior-predictive stage
      }
      log(`${exp.id}: ${stage.key} PASS${r.from_cache ? ' (completed-work check)' : ''}`)
    }

    const critique = await dispatchCritique(exp)
    trail.push({ experiment: exp.id, stage: 'critique', result: critique })
    log(`${exp.id}: critique ${critique ? critique.verdict : 'LOST'}`)
    return {
      id: exp.id,
      root_id: exp0.id,
      status: critique ? 'terminal' : 'agent_lost',
      failed_at: critique ? undefined : 'critique',
      trail,
      critique,
    }
  }
}

log(`Round: ${A.experiments.length} experiment(s), MCMC concurrency ${A.maxMcmcConcurrency ?? 3}, refine budget ${REFINE_BUDGET}`)
const results = (await parallel(A.experiments.map((e) => () => runExperiment(e)))).filter(Boolean)

const terminal = results.filter((r) => r.status === 'terminal')
const attention = results.filter((r) => r.status !== 'terminal')
if (attention.length) log(`${attention.length} experiment(s) need orchestrator triage: ${attention.map((r) => `${r.id} (${r.status} at ${r.failed_at})`).join(', ')}`)

return {
  terminal,
  skipped: attention,
  counts: {
    experiments: A.experiments.length,
    terminal: terminal.length,
    skipped: attention.length,
    cached_stages: results.flatMap((r) => r.trail).filter((t) => t.result && t.result.from_cache).length,
  },
}
